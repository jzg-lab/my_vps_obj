function translated(value: string): string {
  return (
    content[value] ??
    value
      .split(" ")
      .map((word) => names[word] ?? word)
      .join(" ")
  );
}

export function chineseDemoContent(value: unknown): unknown {
  if (typeof value === "string") return translated(value);
  if (Array.isArray(value)) return value.map(chineseDemoContent);
  if (!value || typeof value !== "object") return value;
  const record = value as Record<string, unknown>;
  const result: Record<string, unknown> = Object.fromEntries(
    Object.entries(record).map(([key, item]) => [
      key,
      ["ru", "en", "zh-hans"].includes(key) ? item : chineseDemoContent(item),
    ])
  );
  // Keep the original language variants available in multilingual editors.
  if (typeof record.ru === "string" && !record["zh-hans"] && content[record.ru]) {
    result["zh-hans"] = content[record.ru];
  }
  return result;
}
